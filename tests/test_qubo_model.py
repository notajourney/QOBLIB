"""Run from QOBLIB repo root: python3 -m unittest discover -s tests -p 'test_qubo_model.py' -v"""
from __future__ import annotations

import tempfile
import unittest
from dataclasses import FrozenInstanceError
from decimal import Decimal
from pathlib import Path

from my_code.qubo_reader.model import load_qs, from_qs
from my_code.qubo_reader.qs import parse_qs, QSFormatError
from my_code.qubo_reader.inventory import inventory_row


LABS = """# This file was automatically generated by Zimpl
# param n := 47;
# minimize energy: an explanatory commented formula
# ObjectiveOffset 1
# Vars Non-zeros
3 4
1 2 5004
1 3 -10008
2 3 -10008
3 3 30024
"""

MIS = """# maximize obj: sum x - 2 sum edge x*x;
# ObjectiveOffset 0
# Vars Non-zeros
5 7
1 1 -1
2 2 -1
3 3 -1
4 4 -1
5 5 -1
1 5 1
2 3 1
"""

PORTFOLIO = """# minimize risk: ...
# ObjectiveOffset 9999
# Vars Non-zeros
4 5
1 1 -4
2 2 2
1 2 1
2 3 17
3 4 -3
"""


class ReaderTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name) / "extracted_qb"
        self.root.mkdir()

    def sample(self, family: str, group: str, name: str, body: str) -> Path:
        p = self.root / family / group / f"{name}.qs"
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(body, encoding="utf-8")
        return p

    def test_labs_raw_and_reuse(self):
        p = self.sample("labs", "labs002", "labs002", LABS)
        raw = parse_qs(p)
        q = from_qs(raw, family="labs")
        self.assertEqual(q.num_variables, 3)
        self.assertEqual(q.num_stored_terms, 4)
        self.assertEqual(q.num_interactions, 3)
        self.assertEqual(q.num_diagonal_terms, 1)
        self.assertEqual(q.offset, Decimal("1"))
        self.assertEqual(q.declared_direction, "minimize")
        self.assertEqual(q.stored_direction, "unknown")
        self.assertEqual(q.coefficient_convention, "unverified")
        self.assertEqual(q.raw_diagonal, {3: Decimal("30024")})
        self.assertEqual(q.raw_off_diagonal[(1,2)], Decimal("5004"))
        self.assertEqual(list(q.variables), [1,2,3])
        self.assertIn("# param n := 47;", q.source_comments)
        with self.assertRaises(FrozenInstanceError):
            q.offset = Decimal("0")

    def test_mis_does_not_infer_sense_or_double(self):
        p = self.sample("independentset", "toy", "toy", MIS)
        q = load_qs(p, dataset_root=self.root)
        self.assertEqual(q.family, "independentset")
        self.assertEqual(q.instance_id, "toy/toy")
        self.assertEqual(q.declared_direction, "maximize")
        self.assertEqual(q.stored_direction, "unknown")
        self.assertEqual(q.raw_off_diagonal[(1,5)], Decimal("1"))
        self.assertEqual(q.offset, Decimal("0"))

    def test_missing_diagonals_do_not_reduce_dimension(self):
        p = self.sample("portfolio", "batch", "p", PORTFOLIO)
        q = load_qs(p, dataset_root=self.root)
        self.assertEqual((q.num_variables, q.num_diagonal_terms, q.num_interactions), (4,2,3))
        self.assertEqual(q.num_stored_terms, 5)
        self.assertEqual(list(q.variables), [1,2,3,4])
        self.assertEqual(set(q.raw_diagonal), {1,2})
        self.assertEqual(q.raw_off_diagonal[(3,4)], Decimal("-3"))
        self.assertEqual(q.instance_id, "batch/p")

    def test_absent_variable_is_still_declared(self):
        p = self.sample("labs", "isolated", "i", "# Vars Non-zeros\n4 1\n1 2 7\n")
        q = load_qs(p)
        self.assertEqual(q.num_variables, 4)
        self.assertEqual(q.num_interactions, 1)
        self.assertEqual(list(q.variables), [1,2,3,4])
        self.assertIsNone(q.offset)
        self.assertEqual(q.declared_direction, "unknown")

    def test_legacy_inventory_still_works(self):
        p = self.sample("labs", "labs002", "labs002", LABS)
        row = inventory_row("labs", p, self.root)
        self.assertEqual(row["instance_id"], "labs002/labs002")
        self.assertEqual(row["num_interactions"], 3)
        self.assertEqual(row["structural_validation"], "passed")

    def test_error_cases_inherited_from_qs(self):
        p = self.sample("labs", "bad", "bad", "# Vars Non-zeros\n2 1\n1 3 5\n")
        with self.assertRaises(QSFormatError):
            load_qs(p)
        p.write_text("# Vars Non-zeros\n3 1\n1 2 1\n", encoding="utf-8")
        with self.assertRaises(ValueError):
            load_qs(p, dataset_root=self.root, family="portfolio")


if __name__ == "__main__":
    unittest.main()
